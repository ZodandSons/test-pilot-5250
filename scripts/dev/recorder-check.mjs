import WebSocket from 'ws';
const ws = new WebSocket('ws://localhost:4250/ws');
const q = []; let waiter = null;
ws.on('message', (d) => { const m = JSON.parse(d); if (m.type.startsWith('rec') || m.type === 'error') { if (waiter) { const w = waiter; waiter = null; w(m); } else q.push(m); } });
const next = () => q.length ? Promise.resolve(q.shift()) : new Promise((r) => (waiter = r));
const send = (m) => ws.send(JSON.stringify(m));
await new Promise((r) => ws.on('open', r));
send({ type: 'rec.start', environmentId: 'env_simulator' });
let m = await next(); console.log(m.type, m.screen.text[0].trim());
send({ type: 'rec.input', aid: 'Enter', fields: [{ row: 6, col: 54, value: 'TESTER' }, { row: 7, col: 54, value: 'TESTER1' }] });
m = await next(); console.log(m.type, m.screen.text[0].trim());
send({ type: 'rec.input', aid: 'Enter', fields: [{ row: 20, col: 7, value: '1' }] });
m = await next(); console.log(m.type, m.screen.text[0].trim());
send({ type: 'rec.input', aid: 'Enter', fields: [{ row: 5, col: 31, value: '10002' }] });
m = await next(); console.log(m.type, m.screen.text[0].trim());
send({ type: 'rec.assert', kind: 'text', row: 9, col: 7, length: 7 });
m = await next(); console.log(m.type, m.steps.length);
send({ type: 'rec.input', aid: 'F3', fields: [] });
m = await next();
send({ type: 'rec.stop', save: { name: 'Recorded: Globex orders', suite: 'recorded', tags: ['recorded'] } });
m = await next(); console.log(m.type, m.testId);
const t = await (await fetch(`http://localhost:4250/api/tests/${m.testId}`)).json();
console.log(t.content);
const run = await (await fetch('http://localhost:4250/api/runs', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ testIds: [m.testId], environmentId: 'env_simulator' }) })).json();
await new Promise((r) => setTimeout(r, 2000));
const res = await (await fetch(`http://localhost:4250/api/runs/${run.runId}`)).json();
console.log('playback:', res.status, res.results[0].steps.map((s) => `${s.status[0]} ${s.description}`).join('\n  '));
ws.close();
